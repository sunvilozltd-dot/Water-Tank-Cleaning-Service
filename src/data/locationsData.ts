export const findLocationBySlug = (rawSlug: string): LocationPageData => {
  if (!rawSlug) return LOCATIONS_DATA[0];
  const normalized = rawSlug.toLowerCase().trim().replace(/^water-tank-cleaning-/, '').replace(/-dhaka$/, '');

  const matched = LOCATIONS_DATA.find(l => 
    l.slug === rawSlug ||
    l.slug === normalized ||
    l.areaName.toLowerCase().replace(/[^a-z0-9]/g, '') === normalized.replace(/[^a-z0-9]/g, '') ||
    `water-tank-cleaning-${l.slug}` === rawSlug
  );

  return matched || LOCATIONS_DATA[0];
};
