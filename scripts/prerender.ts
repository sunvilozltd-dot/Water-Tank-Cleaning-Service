async function runPrerender() {
  const distDir = path.resolve(process.cwd(), 'dist');
  const publicDir = path.resolve(process.cwd(), 'public');
  const generatedDir = path.resolve(process.cwd(), 'api/_generated');
  const templatePath = path.join(distDir, 'index.html');

  if (!fs.existsSync(templatePath)) {
    console.error('Error: dist/index.html not found! Run "vite build" first.');
    process.exit(1);
  }

  const baseTemplate = fs.readFileSync(templatePath, 'utf-8');

  // 1. Emit api/_generated/spaTemplate.ts so Vercel SSR routes always use the current hashed Vite assets
  if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
  }
  const templateModuleContent = `// Auto-generated by scripts/prerender.ts during build — DO NOT EDIT MANUALLY.\nexport const SPA_HTML_TEMPLATE = ${JSON.stringify(baseTemplate)};\n`;
  fs.writeFileSync(path.join(generatedDir, 'spaTemplate.ts'), templateModuleContent, 'utf-8');
  console.log('[SEO Prerender] ✓ Updated api/_generated/spaTemplate.ts with hashed Vite assets.');

  // Clean up legacy static public/sitemap.xml & public/llms.txt if present so dynamic /api/* routes are never shadowed
  for (const legacyFile of ['sitemap.xml', 'llms.txt']) {
    const legacyPath = path.join(publicDir, legacyFile);
    if (fs.existsSync(legacyPath)) {
      fs.unlinkSync(legacyPath);
    }
    const copiedDistPath = path.join(distDir, legacyFile);
    if (fs.existsSync(copiedDistPath)) {
      fs.unlinkSync(copiedDistPath);
    }
  }

  // 2. Fetch authoritative Supabase dataset (no bundled article/area merging, explicit status flags)
  const dataset = await fetchLiveSeoDataset();
  const isStrictProd = process.env.STRICT_PRERENDER === 'true' || process.env.VERCEL === '1';

  if (dataset.status.errors.length > 0) {
    console.warn('[SEO Prerender] Database fetch notices:', dataset.status.errors.join(' | '));
  }

  if (isStrictProd && hasUnrecoveredCriticalFailure(dataset.status, CRITICAL_PRERENDER_SLICES)) {
    console.error(
      '[SEO Prerender Error] Critical Supabase slices failed without LKG fallback in strict production mode:',
      JSON.stringify(dataset.status.sliceDetails)
    );
    process.exit(1);
  }

  // Expose live snapshots globally for synchronous React SSR pass (never leak secrets such as indexNowKey)
  const publicSiteConfigSnapshot = dataset.siteConfig
    ? {
        business: dataset.siteConfig.business || undefined,
        announcement: dataset.siteConfig.announcement || undefined,
        hero: dataset.siteConfig.hero || undefined,
        faqs: dataset.siteConfig.faqs || undefined,
        images: dataset.siteConfig.images || undefined,
        seo: dataset.siteConfig.seo ? { ...dataset.siteConfig.seo, indexNowKey: '' } : undefined
      }
    : undefined;

  const initialServicesFaqs =
    dataset.status.configured && isSliceAvailable(dataset.status, 'servicesFaqs')
      ? dataset.servicesFaqs
      : undefined;
  const initialServices =
    dataset.status.configured && isSliceAvailable(dataset.status, 'services')
      ? dataset.services
      : undefined;

  const globalAny = global as any;
  globalAny.window = globalAny.window || {};

  const assignGlobalSnapshot = (key: string, value: any) => {
    if (value !== undefined) {
      globalAny[key] = value;
      globalAny.window[key] = value;
    } else {
      delete globalAny[key];
      delete globalAny.window[key];
    }
  };

  assignGlobalSnapshot('__INITIAL_IMAGE_REGISTRY__', dataset.imageRegistry);
  assignGlobalSnapshot('__INITIAL_HOMEPAGE_SECTIONS__', dataset.homepageSections);
  assignGlobalSnapshot('__HOMEPAGE_REVISION__', dataset.homepageRevision);
  assignGlobalSnapshot('__INITIAL_SERVICES_FAQS__', initialServicesFaqs);
  assignGlobalSnapshot('__INITIAL_SERVICES__', initialServices);
  assignGlobalSnapshot('__INITIAL_SITE_CONFIG__', publicSiteConfigSnapshot);

  const renderAppWithSsrProviders = (initialPath: string) =>
    renderToString(
      React.createElement(
        SsrHomepageSectionsProvider,
        {
          components: ssrHomepageSections,
          children: React.createElement<AppProps>(App, { initialPath, ssrComponents })
        }
      )
    );

  const baseUrl = getCanonicalBaseUrl();
  const routes = buildAllRoutes(dataset);
  console.log(`[SEO Prerender] Prerendering ${routes.length} authoritative routes...`);

  let count = 0;
  for (const route of routes) {
    let renderedRootHtml: string | undefined;
    try {
      renderedRootHtml = renderAppWithSsrProviders(route.path);
    } catch (renderError) {
      console.warn(`[SEO Prerender] SSR component fallback for ${route.path}:`, renderError);
    }

    const pageHtml = renderRouteHtmlFromTemplate(baseTemplate, route, dataset, renderedRootHtml);
    let targetFile: string;
    if (route.path === '/' || route.path === '') {
      targetFile = path.join(distDir, 'index.html');
    } else {
      const cleanPath = route.path.replace(/^\/+/, '');
      const routeDir = path.join(distDir, cleanPath);
      if (!fs.existsSync(routeDir)) {
        fs.mkdirSync(routeDir, { recursive: true });
      }
      targetFile = path.join(routeDir, 'index.html');
    }
    fs.writeFileSync(targetFile, pageHtml, 'utf-8');
    count++;
  }

  // 3. True 404.html fallback
  let notFoundRoot: string | undefined;
  try {
    notFoundRoot = renderAppWithSsrProviders('/404-not-found');
  } catch {
    notFoundRoot = undefined;
  }
  const html404 = render404HtmlFromTemplate(baseTemplate, dataset, notFoundRoot);
  fs.writeFileSync(path.join(distDir, '404.html'), html404, 'utf-8');

  // 4. Write build-time dist/sitemap.xml & dist/llms.txt (while /sitemap.xml and /llms.txt in production route to live /api/*)
  const indexingAllowed = dataset.siteConfig?.seo?.indexingAllowed !== false;
  const sitemapXml = buildSitemapXml(routes, baseUrl, indexingAllowed);
  fs.writeFileSync(path.join(distDir, 'sitemap.xml'), sitemapXml, 'utf-8');

  const llmsTxt = buildLlmsTxt({
    baseUrl,
    siteConfig: dataset.siteConfig,
    services: dataset.services,
    zones: dataset.zones,
    areas: dataset.areas,
    articles: dataset.blogPosts,
    qaItems: PROBLEM_QA_ITEMS
  });
  fs.writeFileSync(path.join(distDir, 'llms.txt'), llmsTxt, 'utf-8');

  // 5. Conditionally generate IndexNow verification file ONLY if INDEXNOW_KEY is set & valid
  const envIndexNowKey = (process.env.INDEXNOW_KEY || '').trim();
  if (!envIndexNowKey) {
    console.log('[SEO Prerender] Notice: INDEXNOW_KEY not set — IndexNow verification file skipped.');
  } else if (/^[a-zA-Z0-9-]{8,128}$/.test(envIndexNowKey)) {
    fs.writeFileSync(path.join(distDir, `${envIndexNowKey}.txt`), envIndexNowKey, 'utf-8');
    console.log(`[SEO Prerender] ✓ Generated IndexNow verification file /${envIndexNowKey}.txt`);
  } else {
    console.warn('[SEO Prerender] Warning: INDEXNOW_KEY format invalid. Verification file skipped.');
  }

  console.log(`[SEO Prerender] ✓ Generated ${count} static pages, dist/404.html, truthful sitemap.xml, and llms.txt.`);
}

runPrerender();
